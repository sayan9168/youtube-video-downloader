#!/usr/bin/env python3
"""Build the static frontend that gets deployed to Cloudflare Pages.

Cloudflare Pages can only serve static files: no Python, no yt-dlp, no ffmpeg.
This script turns the Jinja template plus ``static/`` into a self-contained
``dist/`` folder and writes a runtime ``config.js`` that points the interface at
a separately hosted downloader backend.

Usage:
    python3 scripts/build_pages.py                    # same-origin backend
    python3 scripts/build_pages.py --api-base https://my-api.onrender.com
    PUBLIC_API_BASE=https://my-api.onrender.com python3 scripts/build_pages.py

Then deploy the folder with either the Cloudflare dashboard (build command
``python3 scripts/build_pages.py``, output directory ``dist``) or:

    npx wrangler pages deploy dist --project-name youtube-video-downloader

The generated folder is listed in .gitignore on purpose: it is a build artifact.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config import APP_VERSION, settings  # noqa: E402  (needs sys.path tweak)

try:  # Jinja is optional: the template only needs simple placeholders.
    from jinja2 import Environment, FileSystemLoader, select_autoescape
except ImportError:  # pragma: no cover - exercised in tests by toggling HAS_JINJA
    Environment = None  # type: ignore[assignment]

HEADERS = """\
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: geolocation=(), microphone=(), camera=()
  Content-Security-Policy: default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https:; media-src 'self' blob: https:; connect-src 'self' https: http://localhost:* http://127.0.0.1:*; worker-src 'self'; manifest-src 'self'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'

/config.js
  Cache-Control: no-store

/sw.js
  Cache-Control: no-cache

/static/icons/*
  Cache-Control: public, max-age=604800

/static/*
  Cache-Control: public, max-age=300, must-revalidate

"""

REDIRECTS = """\
# Single page app: every unknown path renders the interface.
/*  /index.html  200
"""


def _clean(value: str) -> str:
    return value.strip().rstrip("/")


def _config_js(api_base: str) -> str:
    return (
        "/* Generated by scripts/build_pages.py - edit that script, not this file. */\n"
        "window.YTD_CONFIG = Object.assign({ apiBase: %s }, window.YTD_CONFIG || {});\n"
        % json.dumps(_clean(api_base))
    )


def _context() -> dict:
    return {
        "version": APP_VERSION,
        "demo": settings.demo_mode,
        "max_playlist_entries": settings.max_playlist_entries,
        "default_lang": "en",
    }


def _simple_render(raw: str, context: dict) -> str:
    """Render the handful of ``{{ name }}`` placeholders without Jinja."""

    def replace(match: re.Match) -> str:
        key = match.group(1).strip()
        if key not in context:
            raise SystemExit(
                f"templates/index.html uses {{{{{key}}}}}, which the static build cannot fill in. "
                "Install jinja2 (pip install jinja2) or remove the placeholder."
            )
        return str(context[key])

    rendered = re.sub(r"\{\{\s*([^{}]+?)\s*\}\}", replace, raw)
    if "{%" in rendered:
        raise SystemExit(
            "templates/index.html contains Jinja statements; install jinja2 (pip install jinja2) to build."
        )
    return rendered


def _render_index(dest: Path) -> None:
    context = _context()
    if Environment is not None:
        env = Environment(
            loader=FileSystemLoader(str(ROOT / "templates")),
            autoescape=select_autoescape(("html", "xml")),
        )
        html = env.get_template("index.html").render(**context)
    else:
        html = _simple_render((ROOT / "templates" / "index.html").read_text(encoding="utf-8"), context)
    (dest / "index.html").write_text(html, encoding="utf-8")


def build(out_dir: Path, api_base: str) -> Path:
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    _render_index(out_dir)

    # Everything under static/ is served from /static/ exactly like the backend does.
    shutil.copytree(ROOT / "static", out_dir / "static")

    # Files the backend normally exposes at the site root.
    for name in ("sw.js", "manifest.webmanifest"):
        shutil.copy2(ROOT / "static" / name, out_dir / name)
    favicon = ROOT / "static" / "icons" / "favicon.ico"
    if favicon.is_file():
        shutil.copy2(favicon, out_dir / "favicon.ico")

    # Runtime configuration + Cloudflare Pages metadata.
    (out_dir / "config.js").write_text(_config_js(api_base), encoding="utf-8")
    (out_dir / "_headers").write_text(HEADERS, encoding="utf-8")
    (out_dir / "_redirects").write_text(REDIRECTS, encoding="utf-8")

    missing = [
        str(path.relative_to(out_dir))
        for path in (
            out_dir / "static" / "icons" / "icon-192.png",
            out_dir / "static" / "js" / "app.js",
            out_dir / "static" / "css" / "app.css",
        )
        if not path.is_file()
    ]
    if missing:
        print("warning: expected assets are missing: " + ", ".join(missing), file=sys.stderr)

    return out_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--api-base",
        default=None,
        help="Absolute URL of the downloader backend (default: PUBLIC_API_BASE or empty = same origin)",
    )
    parser.add_argument("--out", default="dist", help="Output directory (default: dist)")
    args = parser.parse_args(argv)

    api_base = args.api_base if args.api_base is not None else settings.public_api_base
    out_dir = Path(args.out)
    if not out_dir.is_absolute():
        out_dir = ROOT / out_dir

    build(out_dir, api_base)

    files = sum(1 for path in out_dir.rglob("*") if path.is_file())
    print(f"Built {files} files into {out_dir}")
    if _clean(api_base):
        print(f"Backend URL baked into config.js: {_clean(api_base)}")
    else:
        print("config.js uses the same origin; set the backend URL in the UI settings dialog.")
    print('Deploy with: npx wrangler pages deploy "%s" --project-name youtube-video-downloader' % out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
